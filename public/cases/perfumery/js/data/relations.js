const key = (a, b) => [a, b].sort().join('|');
const INDEX = new Map(RELATIONS.map(r => [key(r.a, r.b), r]));

export function relationFor(famA, famB) {
  if (famA === famB) return null;
  return INDEX.get(key(famA, famB)) || null;
}

